package com.volna.player.player

/**
 * Когда ждать перед очередной попыткой переподключения.
 *
 * Отдельный объект, а не константа в ViewModel, потому что ждать приходится
 * минутами и паузу невозможно отладить «на глаз».
 *
 * Лимита попыток нет намеренно. Раньше он был равен трём, но из-за сброса
 * счётчика не срабатывал ни разу — переподключение шло бесконечно с
 * постоянной паузой 700 мс. Если счётчик починить, а лимит оставить,
 * выйдет хуже прежнего: три попытки за ~4 секунды, потом тишина, и поток
 * не загрузится вообще. YouTube отдаёт 403 не по расписанию, а по
 * состоянию ссылки, поэтому единственный способ выбраться — продолжать.
 */
object ReconnectPolicy {

    /** Первая пауза; дальше растёт, чтобы не долбить YouTube раз в секунду. */
    private const val STEP_MS = 700L

    /**
     * Потолок паузы.
     *
     * Дальше расти незачем: пользователь всё равно не успевает решить, что
     * делать, а ждать по полчаса — значит забыть, что музыка вообще играла.
     */
    private const val MAX_DELAY_MS = 10_000L

    /** Пауза перед попыткой [attempt] (нумерация с единицы). */
    fun delayMs(attempt: Int): Long =
        (STEP_MS * attempt.coerceAtLeast(1)).coerceAtMost(MAX_DELAY_MS)
}
