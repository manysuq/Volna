package com.volna.player.player

/**
 * Гасить ли сервис, когда система убирает задачу.
 *
 * Отдельный объект потому, что решение принимается в момент, когда отладить
 * его уже нечем: если ответ неверный, сервис умирает вместе с музыкой.
 */
internal object ServiceSurvival {

    /**
     * Оставляем ли сервис жить.
     *
     * Ключевой момент — [playWhenReady] вместо «звук идёт сейчас». Звук
     * прерывается на каждую буферизацию и подавление, а намерение пользователя
     * остаётся прежним. По старому правилу достаточно было одного момента
     * тишины посреди песни, чтобы сервис убить навсегда.
     */
    fun shouldKeepAlive(playWhenReady: Boolean, mediaItemCount: Int): Boolean =
        playWhenReady && mediaItemCount > 0
}
