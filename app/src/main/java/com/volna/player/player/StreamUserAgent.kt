package com.volna.player.player

/**
 * User-Agent, которым сейчас надо открывать ссылки на поток.
 *
 * Отдельный объект потому, что он один на сервис, а меняется на каждый трек:
 * подпись ссылки привязана к InnerTube-клиенту, который её выдал, и открывать
 * её надо именно его User-Agent'ом. Раньше агент был зашит в DataSource при
 * создании плеера, и ссылка от любого другого клиента открывалась чужим.
 */
internal class StreamUserAgent {

    /** Текущий агент, либо null — тогда остаётся зашитый в DataSource. */
    @Volatile
    var value: String? = null
}
