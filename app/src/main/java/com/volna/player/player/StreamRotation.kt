package com.volna.player.player

/**
 * Когда менять ссылку на поток.
 *
 * Ссылка выдаётся с ограничением по объёму: проверено на живых ссылках,
 * 512 КБ отдаются, а запрос на мегабайт получает 403. Проверка ссылки чинит
 * только начало трека — обрыв приходит в середине, и на него приходится
 * переподключаться, то есть музыка всё равно прерывается.
 *
 * Поэтому ссылку меняем заранее, не дожидаясь отказа: разрыв не слышен,
 * потому что новый адрес уже готов, когда старый кончился.
 */
internal object StreamRotation {

    /**
     * Сколько байт можно взять с одной ссылки.
     *
     * Замеры шли от 512 КБ (проходит) до 1 МБ (отказ), поэтому берём
     * заведомо ниже порога: недобрав немного обернётся лишним обновлением
     * ссылки, а перебрав — обрывом посреди песни.
     */
    const val ROTATE_AFTER_BYTES = 400L * 1024L

    /**
     * Нужно ли обновлять ссылку.
     *
     * [forced] — после отказа 403: там сомневаться не в чем, ссылка уже
     * негодная, и ждать следующего обновления незачем.
     */
    fun shouldRotate(consumedBytes: Long, forced: Boolean): Boolean =
        forced || consumedBytes >= ROTATE_AFTER_BYTES
}
