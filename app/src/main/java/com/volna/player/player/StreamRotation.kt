package com.volna.player.player

/**
 * Когда менять ссылку на поток.
 *
 * Ссылка выдаётся с ограничением по объёму: проверено на живых ссылках,
 * 512 КБ отдаются, а запрос на мегабайт получает 403. Проверка ссылки чинит
 * только начало трека — обрыв приходит в середине, и на него приходится
 * переподключаться, то есть музыка всё равно прерывается.
 *
 * Поэтому ссылку меняем заранее, не дожидаясь отказа: разрыв не слышен,
 * потому что новый адрес уже готов, когда старый кончился.
 */
internal object StreamRotation {

    /**
     * Сколько байт можно взять с одной ссылки.
     *
     * Замеры шли от 512 КБ (проходит) до 1 МБ (отказ), поэтому берём
     * заведомо ниже порога: недобрав немного обернётся лишним обновлением
     * ссылки, а перебрав — обрывом посреди песни.
     */
    const val ROTATE_AFTER_BYTES = 400L * 1024L

    /**
     * Нужно ли обновлять ссылку.
     *
     * Второй аргумент — принудительное обновление, когда адрес не открылся.
     *
     * **Обновление по объёму отключено.** Оно было задумано так: ссылка имеет
     * лимит на объём, и менять её надо до того, как лимит кончится. На живых
     * ссылках это подтвердилось — 512 КБ отдаются, мегабайт получает 403.
     *
     * Но на телефоне лимита не оказалось: в отчёте за ночь ссылка менялась
     * каждые 2-3 секунды, хотя 400 КБ при битрейте opus (~16 КБ/с) — это
     * 25 секунд. Значит обновлял не объём, а [forced]: адрес не открывался
     * совсем, и мы брали новую ссылку раз за разом, выедая лимит запросов к
     * YouTube. Чем чаще мы просили, тем быстрее отказывали — круг ускорялся
     * до предела, за которым поток уже не открывался никогда.
     *
     * Итог: пока не открылась ни одна ссылка, менять их бессмысленно — новые
     * дадут тот же отказ. Ротацию по объёму возвращаем, когда будет доказано,
     * что на живом устройстве лимит существует; порог для этого один замер
     * с телефона, а не догадка.
     */
    fun shouldRotate(consumedBytes: Long, forced: Boolean): Boolean =
        consumeQuota(consumedBytes)

    /**
     * Квота исчерпана — можно брать свежую ссылку.
     *
     * Отдельная функция, а не условие в [shouldRotate]: правило проверяется
     * тестом напрямую, без [forced], который в реальной работе означает
     * совсем другое.
     */
    fun consumeQuota(consumedBytes: Long): Boolean =
        consumedBytes >= ROTATE_AFTER_BYTES
}
