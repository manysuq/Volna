package com.volna.player.player

/**
 * Считает, сколько замеров подряд плеер стоит на месте.
 *
 * Отдельный объёмом потому, что правило обязано быть проверяемым: зависание
 * воспроизведения воспроизвести в тесте нельзя, а вот решение «это ещё не
 * зависание» — можно. Именно это решение важно: лишний перезапуск потока рвёт
 * музыку, а слишком поздний оставляет пользователя слушать тишину.
 */
internal object StallDetector {

    /**
     * Новая длина полосы застоя.
     *
     * [playing] — `playWhenReady`: на паузе и после конца трека позиция стоит
     * законно, и застоя там нет. [position] и [lastPosition] — замеры подряд.
     *
     * Перемотка назад ([position] меньше прошлого) застоем не считается: это
     * действие пользователя, а не остановка потока.
     */
    fun nextStreak(playing: Boolean, position: Long, lastPosition: Long, streak: Int): Int = when {
        !playing -> 0
        position > lastPosition -> 0
        position == lastPosition -> streak + 1
        else -> 0
    }
}
