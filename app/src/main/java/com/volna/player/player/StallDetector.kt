package com.volna.player.player

/**
 * Считает, сколько замеров подряд плеер стоит на месте.
 *
 * Отдельный объёмом потому, что правило обязано быть проверяемым: зависание
 * воспроизведения воспроизвести в тесте нельзя, а вот решение «это ещё не
 * зависание» — можно. Именно это решение и оказалось главным: раньше
 * сторож смотрел только на playWhenReady и объявлял зависанием обычную паузу
 * между переподключениями.
 */
internal object StallDetector {

    /** Плеер готов играть, но не играет: это и есть зависание. */
    const val STATE_READY = 3

    /** Плеер ничего не делает: так бывает между переподключениями. */
    const val STATE_IDLE = 1

    /** Дослушан до конца: дальше идти некуда. */
    const val STATE_ENDED = 4

    /**
     * Новая длина полосы застоя.
     *
     * [playing] — `playWhenReady`: на паузе пользователь сам её снял.
     * [state] — состояние плеера. Простой и конец — не зависание: там
     * приложение само остановило поток, чтобы переподключиться, и ждать
     * нечего. Без этой проверки каждое переподключение порождало ещё и
     * ложное «зависание», а оно — ещё один запрос к YouTube, от чего
     * отказы приходили чаще.
     *
     * Перемотка назад ([position] меньше прошлого) застоем не считается: это
     * действие пользователя.
     */
    fun nextStreak(
        playing: Boolean,
        state: Int,
        position: Long,
        lastPosition: Long,
        streak: Int,
    ): Int = when {
        !playing -> 0
        state == STATE_IDLE -> 0
        state == STATE_ENDED -> 0
        position > lastPosition -> 0
        position == lastPosition -> streak + 1
        else -> 0
    }
}
